"""One-shot setup for a Windows workstation (e.g. CF-20); also works on Linux/macOS.

Run by setup_cf20.bat with whatever Python it found (system Python or the
one bundled with Houdini). Steps:
  1. check Python + repo + vendored front-end libs (no Node/npm needed)
  2. find Houdini installs, write <prefs>/packages/geobox.json for each version
  3. make sure the sample project exists
  4. run the unit tests (skip with --no-tests)
  5. write tools/geobox_env.bat (interpreter + UTF-8 settings) for the other .bat files
  6. write setup_report.txt (send it back if anything fails)
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import os
import platform
import socket
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))

import find_houdini  # noqa: E402

LINES = []


def say(msg=""):
    LINES.append(msg)
    try:
        print(msg, flush=True)
    except UnicodeEncodeError:  # very old consoles
        print(msg.encode("ascii", "replace").decode("ascii"), flush=True)


def ok(msg):
    say("  [OK]   " + msg)


def warn(msg):
    say("  [!!]   " + msg)


def fail(msg):
    say("  [FAIL] " + msg)


def bat_quote(value: str) -> str:
    return value.replace("%", "%%")


def write_env_bat(path: str, env: dict):
    lines = ["@echo off", "rem generated by tools/setup_cf20.py - safe to delete (setup recreates it)"]
    lines += ['set "%s=%s"' % (k, bat_quote(v)) for k, v in env.items() if v]
    with open(path, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("\n".join(lines) + "\n")


def port_free(port: int, host="127.0.0.1") -> bool:
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.settimeout(0.5)
        return s.connect_ex((host, port)) != 0
    finally:
        s.close()


def step_python():
    say("1) Python / 專案檔案")
    v = sys.version_info
    if v < (3, 9):
        fail("Python %d.%d is too old (need 3.9+): %s" % (v[0], v[1], sys.executable))
        return False
    ok("Python %s  (%s)" % (platform.python_version(), sys.executable))
    ok("repo: %s" % ROOT)
    man = os.path.join(ROOT, "viewer", "vendor", "manifest.json")
    if os.path.exists(man):
        with open(man, "r", encoding="utf-8") as fh:
            vers = json.load(fh).get("versions", {})
        ok("前端套件已內附 viewer/vendor (" + ", ".join("%s@%s" % kv for kv in vers.items()) + ")，不需要 Node/npm")
    else:
        fail("viewer/vendor 不存在：請重新下載完整的 repo")
        return False
    return True


def step_houdini(dry_run=False):
    say("2) Houdini")
    found = find_houdini.installs()
    if not found:
        warn("找不到 Houdini 安裝（Web 預覽仍可用；裝好 Houdini 後再跑一次 setup）")
        return [], []
    for d in found:
        ok("Houdini %s  %s%s" % (d["version"], d["hfs"], "  (from $HFS)" if d.get("from_env") else ""))
    try:
        from geobox import houdini_install
    except Exception as exc:  # noqa: BLE001
        fail("cannot import geobox.houdini_install: %s" % exc)
        return found, []
    prefs = []
    for d in found:
        p = find_houdini.pref_dir_for(d["major_minor"])
        if p not in prefs:
            prefs.append(p)
    written = []
    for p in prefs:
        if dry_run:
            ok("(dry-run) would write %s" % os.path.join(p, "packages", "geobox.json"))
            continue
        try:
            written += houdini_install.install(p)
        except Exception as exc:  # noqa: BLE001
            fail("package for %s: %s" % (p, exc))
    for w in written:
        ok("Houdini package -> %s" % w)
    if written:
        say("        重開 Houdini 後會出現 GeoBox shelf（找不到時：shelf 區右鍵 > Shelves > GeoBox）")
    return found, written


def step_sample():
    say("3) 範例專案")
    scene = os.path.join(ROOT, "projects", "sample_synthetic", "scene.json")
    if os.path.exists(scene):
        ok("projects/sample_synthetic 已存在")
        return True
    try:
        from geobox import project
        project.build("sample_synthetic", (25.04, 121.52), (600, 600),
                      osm_file=os.path.join(ROOT, "tests", "fixtures", "sample_osm.json"), log=lambda *a: None)
        ok("已產生 projects/sample_synthetic")
        return True
    except Exception as exc:  # noqa: BLE001
        fail("產生範例專案失敗: %s" % exc)
        return False


def step_tests(skip: bool):
    say("4) 單元測試")
    if skip:
        warn("略過 (--no-tests)")
        return True
    env = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUTF8="1")
    cmd = [sys.executable, "-W", "ignore", "-m", "unittest", "discover", "-s", "tests"]
    try:
        r = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=900)
    except subprocess.TimeoutExpired:
        fail("tests timed out")
        return False
    tail = [ln for ln in (r.stderr or "").splitlines() if ln.strip()][-3:]
    if r.returncode == 0:
        ok("全部通過  " + " / ".join(t for t in tail if t.startswith("Ran")))
        return True
    fail("有測試失敗（詳細內容在 setup_report.txt）")
    LINES.append("---- test output (tail) ----")
    LINES.extend((r.stderr or "").splitlines()[-80:])
    LINES.append("----")
    return False


def main(argv=None):
    ap = argparse.ArgumentParser(description="GeoBox workstation setup")
    ap.add_argument("--no-tests", action="store_true", help="skip unit tests")
    ap.add_argument("--quick", action="store_true", help="same as --no-tests (used by the start scripts)")
    ap.add_argument("--dry-run", action="store_true", help="don't write the Houdini package")
    ap.add_argument("--report", default=os.path.join(ROOT, "setup_report.txt"))
    a = ap.parse_args(argv)

    say("GeoBox setup  %s  %s  %s" % (_dt.datetime.now().isoformat(timespec="seconds"),
                                      platform.platform(), socket.gethostname()))
    say("=" * 72)
    good = step_python()
    found, written = step_houdini(a.dry_run) if good else ([], [])
    good = step_sample() and good
    tests_ok = step_tests(a.no_tests or a.quick) if good else False

    hython = next((d["hython"] for d in found if d.get("hython")), "")
    env = {"GEOBOX_PY": sys.executable, "GEOBOX_ROOT": ROOT, "GEOBOX_HYTHON": hython,
           "PYTHONIOENCODING": "utf-8", "PYTHONUTF8": "1"}
    env_bat = os.path.join(ROOT, "tools", "geobox_env.bat")
    write_env_bat(env_bat, env)
    say("5) 環境")
    ok("tools/geobox_env.bat  (GEOBOX_PY=%s)" % sys.executable)
    if not port_free(8765):
        warn("port 8765 已被使用（可能 GeoBox 已在執行；start_geobox.bat 會直接開瀏覽器）")

    say("=" * 72)
    if good and tests_ok:
        say("完成 ✔  下一步：")
    else:
        say("完成，但有項目需要處理（見上方 [FAIL]/[!!]，並把 setup_report.txt 傳給我）。下一步：")
    say("  • 雙擊 start_geobox.bat          → 瀏覽器開啟 Web 預覽 (http://127.0.0.1:8765)")
    if found:
        say("  • 開 Houdini → GeoBox shelf      → City Box (SOP) / Solaris / Sky")
        say("  • 雙擊 run_houdini_selftest.bat  → 在真的 Houdini 裡自動測試，產生 selftest\\selftest_report.txt")
    say("  • farm 節點：雙擊 run_farm_worker.bat（共享資料夾路徑）")
    try:
        with open(a.report, "w", encoding="utf-8") as fh:
            fh.write("\n".join(LINES) + "\n")
        say("報告：%s" % a.report)
    except OSError as exc:
        warn("cannot write report: %s" % exc)
    return 0 if good else 1


if __name__ == "__main__":
    sys.exit(main())
